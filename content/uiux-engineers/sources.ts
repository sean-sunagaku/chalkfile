/** 出典の id から、講座サイトの「出典・参考資料」タブに出す形にする */
export const docsOf = (ids: string[]): Lecture['docs'] =>
  ids.map((id) => {
    const s = UIUX_SOURCES.find((x) => x.id === id);
    if (!s) throw new Error(`出典が無い: ${id}`);
    return { title: `${s.publisher}（${s.year}）${s.title}`, url: s.url };
  });
